    fn emit_region_requirement(
        &self,
        lhs: &Expr,
        op: CmpOp,
        rhs: f64,
    ) -> Result<String, CodegenError> {
        match lhs {
            Expr::EventScalar(branch) => {
                let branch_type = self.branch_type(branch)?;
                if branch_type == BranchType::Bool {
                    let branch = rust_string(branch);
                    Ok(bool_comparison_expr(
                        format!("event.scalar::<bool>({branch})?"),
                        op,
                        rhs,
                        "region requirement",
                    )?)
                } else {
                    Ok(format!(
                        "{} {} {}",
                        self.emit_event_scalar_numeric_expr(branch, branch_type)?,
                        cmp_op(op),
                        f64_literal(rhs)
                    ))
                }
            }
            Expr::Literal(_) | Expr::Binary { .. } | Expr::Abs(_) | Expr::Sqrt(_) => Ok(format!(
                "{} {} {}",
                self.emit_output_expr(lhs, "region_requirement")?,
                cmp_op(op),
                f64_literal(rhs)
            )),
            Expr::Count(object) => {
                let lhs = count_ident(object)?;
                let rhs = checked_count_rhs(rhs, "region requirement")?;
                Ok(format!("{lhs} {} {rhs}_u32", cmp_op(op)))
            }
            Expr::CountWhere { object, predicate } => {
                let selected = selected_objects_ident(object)?;
                let item = format!("{}_count_item", checked_ident(object, "count object")?);
                let predicate = self.emit_selected_predicate(object, &item, predicate)?;
                let rhs = checked_count_rhs(rhs, "region requirement")?;
                Ok(format!(
                    "({selected}.iter().filter(|{item}| {predicate}).count() as u32) {} {rhs}_u32",
                    cmp_op(op)
                ))
            }
            Expr::SumAttr { object, attr } => {
                let selected = selected_objects_ident(object)?;
                let item = format!("{}_sum_item", checked_ident(object, "sum object")?);
                let attr = checked_ident(attr, "sum attribute")?;
                Ok(format!(
                    "{selected}.iter().map(|{item}| {item}.{attr} as f64).sum::<f64>() {} {}",
                    cmp_op(op),
                    f64_literal(rhs)
                ))
            }
            Expr::LeadingAttr { object, attr } => {
                let selected = selected_objects_ident(object)?;
                let item = format!("{}_leading_item", checked_ident(object, "leading object")?);
                let attr = checked_ident(attr, "leading attribute")?;
                Ok(format!(
                    "{selected}.iter().map(|{item}| {item}.{attr} as f64).reduce(f64::max).is_some_and(|value| value {} {})",
                    cmp_op(op),
                    f64_literal(rhs)
                ))
            }
            Expr::All { object, predicate } => {
                let predicate = self.emit_collection_bool_expr("all", object, predicate)?;
                Ok(bool_comparison_expr(
                    predicate,
                    op,
                    rhs,
                    "region requirement",
                )?)
            }
            Expr::Any { object, predicate } => {
                let predicate = self.emit_collection_bool_expr("any", object, predicate)?;
                Ok(bool_comparison_expr(
                    predicate,
                    op,
                    rhs,
                    "region requirement",
                )?)
            }
            Expr::EitherPairPt {
                left,
                right,
                leading,
                subleading,
            } => {
                let predicate =
                    self.emit_either_pair_pt_expr(left, right, leading.value, subleading.value)?;
                Ok(bool_comparison_expr(
                    predicate,
                    op,
                    rhs,
                    "region requirement",
                )?)
            }
            Expr::ClosestMass {
                left,
                right,
                target,
            } => Ok(format!(
                "{} {} {}",
                self.emit_ordered_mass_expr(left, right, target.value, true)?,
                cmp_op(op),
                f64_literal(rhs)
            )),
            Expr::OtherMass {
                left,
                right,
                target,
            } => Ok(format!(
                "{} {} {}",
                self.emit_ordered_mass_expr(left, right, target.value, false)?,
                cmp_op(op),
                f64_literal(rhs)
            )),
            Expr::ZepVv {
                system,
                met_pt,
                met_phi,
                dijet,
            } => Ok(format!(
                "{} {} {}",
                self.emit_zep_vv_expr(system, met_pt, met_phi, dijet)?,
                cmp_op(op),
                f64_literal(rhs)
            )),
            Expr::SystemMetEta {
                system,
                met_pt,
                met_phi,
            } => Ok(format!(
                "{} {} {}",
                self.emit_system_met_eta_expr(system, met_pt, met_phi)?,
                cmp_op(op),
                f64_literal(rhs)
            )),
            Expr::SystemMetPt {
                system,
                met_pt,
                met_phi,
            } => Ok(format!(
                "{} {} {}",
                self.emit_system_met_pt_expr(system, met_pt, met_phi)?,
                cmp_op(op),
                f64_literal(rhs)
            )),
            Expr::SystemPairMetPt {
                system,
                met_pt,
                met_phi,
                pair,
            } => Ok(format!(
                "{} {} {}",
                self.emit_system_pair_met_pt_expr(system, met_pt, met_phi, pair)?,
                cmp_op(op),
                f64_literal(rhs)
            )),
            Expr::SystemPairPtBalance {
                system,
                met_pt,
                met_phi,
                pair,
            } => Ok(format!(
                "{} {} {}",
                self.emit_system_pair_pt_balance_expr(system, met_pt, met_phi, pair)?,
                cmp_op(op),
                f64_literal(rhs)
            )),
            Expr::MetType1Pt {
                jets,
                met_pt,
                met_phi,
                nominal_pt,
                shifted_pt,
            } => Ok(format!(
                "{} {} {}",
                self.emit_met_type1_expr(jets, met_pt, met_phi, nominal_pt, shifted_pt, true)?,
                cmp_op(op),
                f64_literal(rhs)
            )),
            Expr::MetType1Phi {
                jets,
                met_pt,
                met_phi,
                nominal_pt,
                shifted_pt,
            } => Ok(format!(
                "{} {} {}",
                self.emit_met_type1_expr(jets, met_pt, met_phi, nominal_pt, shifted_pt, false)?,
                cmp_op(op),
                f64_literal(rhs)
            )),
            Expr::SystemDeltaPhi { left, right } => Ok(format!(
                "{} {} {}",
                self.emit_system_delta_phi_expr(left, right)?,
                cmp_op(op),
                f64_literal(rhs)
            )),
            Expr::LegacyLeptonRpt {
                muons,
                electrons,
                dijet,
            } => Ok(format!(
                "{} {} {}",
                self.emit_legacy_lepton_rpt_expr(muons, electrons, dijet)?,
                cmp_op(op),
                f64_literal(rhs)
            )),
            Expr::PairConstituentAttr { pair, attr, rank } => Ok(format!(
                "{} {} {}",
                self.emit_pair_constituent_attr_expr(pair, attr, *rank)?,
                cmp_op(op),
                f64_literal(rhs)
            )),
            Expr::ZepMax { system, dijet } => Ok(format!(
                "{} {} {}",
                self.emit_zep_max_expr(system, dijet)?,
                cmp_op(op),
                f64_literal(rhs)
            )),
            Expr::Attr { object, attr } if self.derived_object(object).is_ok() => {
                let lhs = derived_attr_expr(object, attr)?;
                Ok(format!("{lhs} {} {}", cmp_op(op), f64_literal(rhs)))
            }
            other => Err(CodegenError::UnsupportedFeature(format!(
                "region requirement `{other}` is not supported by this slice"
            ))),
        }
    }

    fn emit_lumi_mask_condition(&self, mask: &crate::LumiMask) -> Result<String, CodegenError> {
        let mut arms = Vec::new();
        for (run, ranges) in mask.ranges_by_run() {
            let ranges = ranges
                .iter()
                .map(|range| {
                    format!(
                        "nano_spec::LumiRange {{ start: {}_u32, end: {}_u32 }}",
                        range.start, range.end
                    )
                })
                .collect::<Vec<_>>()
                .join(", ");
            arms.push(format!(
                "{run}_u32 => nano_spec::lumi_mask_contains_ranges(&[{ranges}], luminosity_block)"
            ));
        }
        let match_arms = if arms.is_empty() {
            "_ => false".to_string()
        } else {
            format!("{}, _ => false", arms.join(", "))
        };
        Ok(format!(
            "event.is_mc() || {{ let run = event.scalar::<u32>(\"run\")?; let luminosity_block = event.scalar::<u32>(\"luminosityBlock\")?; match run {{ {match_arms} }} }}"
        ))
    }

