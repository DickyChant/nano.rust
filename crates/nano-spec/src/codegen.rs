fn collect_derived_objects_in_expr(
    expr: &Expr,
    spec: &AnalysisSpec,
    objects: &mut BTreeSet<String>,
) {
    match expr {
        Expr::Attr { object, .. }
            if spec
                .derived_objects
                .iter()
                .any(|derived| derived.name == *object) =>
        {
            objects.insert(object.clone());
        }
        Expr::Abs(inner) | Expr::Sqrt(inner) => {
            collect_derived_objects_in_expr(inner, spec, objects)
        }
        Expr::Binary { lhs, rhs, .. } => {
            collect_derived_objects_in_expr(lhs, spec, objects);
            collect_derived_objects_in_expr(rhs, spec, objects);
        }
        Expr::CountWhere { predicate, .. }
        | Expr::All { predicate, .. }
        | Expr::Any { predicate, .. } => {
            collect_derived_objects_in_expr(&predicate.lhs, spec, objects);
        }
        Expr::ClosestMass { left, right, .. } | Expr::OtherMass { left, right, .. } => {
            if spec
                .derived_objects
                .iter()
                .any(|derived| derived.name == *left)
            {
                objects.insert(left.clone());
            }
            if spec
                .derived_objects
                .iter()
                .any(|derived| derived.name == *right)
            {
                objects.insert(right.clone());
            }
        }
        Expr::ZepVv { system, dijet, .. } => {
            if spec
                .derived_objects
                .iter()
                .any(|derived| derived.name == *system)
            {
                objects.insert(system.clone());
            }
            if spec
                .derived_objects
                .iter()
                .any(|derived| derived.name == *dijet)
            {
                objects.insert(dijet.clone());
            }
        }
        Expr::SystemMetEta { system, .. } | Expr::SystemMetPt { system, .. } => {
            if spec
                .derived_objects
                .iter()
                .any(|derived| derived.name == *system)
            {
                objects.insert(system.clone());
            }
        }
        Expr::SystemPairMetPt { system, pair, .. }
        | Expr::SystemPairPtBalance { system, pair, .. } => {
            if spec
                .derived_objects
                .iter()
                .any(|derived| derived.name == *system)
            {
                objects.insert(system.clone());
            }
            if spec
                .derived_objects
                .iter()
                .any(|derived| derived.name == *pair)
            {
                objects.insert(pair.clone());
            }
        }
        Expr::SystemDeltaPhi { left, right } => {
            if spec
                .derived_objects
                .iter()
                .any(|derived| derived.name == *left)
            {
                objects.insert(left.clone());
            }
            if spec
                .derived_objects
                .iter()
                .any(|derived| derived.name == *right)
            {
                objects.insert(right.clone());
            }
        }
        Expr::LegacyLeptonRpt { dijet, .. } => {
            if spec
                .derived_objects
                .iter()
                .any(|derived| derived.name == *dijet)
            {
                objects.insert(dijet.clone());
            }
        }
        Expr::PairConstituentAttr { pair, .. } => {
            if spec
                .derived_objects
                .iter()
                .any(|derived| derived.name == *pair)
            {
                objects.insert(pair.clone());
            }
        }
        Expr::ZepMax { system, dijet } => {
            if spec
                .derived_objects
                .iter()
                .any(|derived| derived.name == *system)
            {
                objects.insert(system.clone());
            }
            if spec
                .derived_objects
                .iter()
                .any(|derived| derived.name == *dijet)
            {
                objects.insert(dijet.clone());
            }
        }
        _ => {}
    }
}

fn expr_counts_object(expr: &Expr, object_name: &str) -> bool {
    match expr {
        Expr::Count(object) => object == object_name,
        Expr::CountWhere { object, .. } => object == object_name,
        Expr::Abs(inner) | Expr::Sqrt(inner) => expr_counts_object(inner, object_name),
        Expr::Binary { lhs, rhs, .. } => {
            expr_counts_object(lhs, object_name) || expr_counts_object(rhs, object_name)
        }
        _ => false,
    }
}

